class Character {
  final String name;
  final String gender;
  final int age;
  final String imagePath;
  final String background;
  final String personality;
  final String tone;
  final String slogan;

  Character({
    required this.name,
    required this.gender,
    required this.age,
    required this.imagePath,
    required this.background,
    required this.personality,
    required this.tone,
    required this.slogan,
  });
}